// Offline play (post-Milestone 9): a tiny Vite plugin that writes sw.js into
// the build. The worker precaches everything the game needs - the bundle,
// index.html and every file in public/ (sounds, music, icons) - so after one
// visit the game opens without a connection. No dependencies: the list of
// files and a content hash (the cache version) are computed at build time.
//
// Plain JavaScript on purpose: it reads public/ with node:fs, and the config's
// type-check has no Node types (see vite.config.ts). Types: offline-plugin.d.mts.

import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { createHash } from 'node:crypto'

function listFiles(dir) {
  const out = []
  const walk = (current) => {
    for (const name of readdirSync(current)) {
      const full = join(current, name)
      if (statSync(full).isDirectory()) walk(full)
      else out.push(relative(dir, full).split(sep).join('/'))
    }
  }
  try {
    walk(dir)
  } catch {
    // No public directory: nothing to add.
  }
  return out
}

/** @returns {import('vite').Plugin} */
export function offline() {
  let publicDir = 'public'
  return {
    name: 'common-ground-offline',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      publicDir = config.publicDir
    },
    generateBundle(_options, bundle) {
      const hash = createHash('sha256')
      const built = Object.keys(bundle).filter((name) => !name.endsWith('.map')).sort()
      for (const name of built) {
        const item = bundle[name]
        hash.update(name)
        hash.update(item.type === 'chunk' ? item.code : item.source)
      }
      const publicFiles = listFiles(publicDir).sort()
      for (const name of publicFiles) {
        hash.update(name)
        hash.update(readFileSync(join(publicDir, name)))
      }
      const files = [...new Set(['./', 'index.html', ...built, ...publicFiles])].filter((f) => f !== 'sw.js')
      const version = hash.digest('hex').slice(0, 12)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(files, version) })
    },
  }
}

function serviceWorker(files, version) {
  return `// Generated by scripts/offline-plugin.mjs - do not edit.
const CACHE = 'common-ground-${version}'
const FILES = ${JSON.stringify(files)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES.map((file) => new URL(file, self.registration.scope)))),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('common-ground-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

// The page asks a waiting worker to take over when the player chooses to reload.
self.addEventListener('message', (event) => {
  if (event.data === 'skipWaiting') self.skipWaiting()
})

// <audio> asks for byte ranges; answer them from the cached file.
async function ranged(request, response) {
  const range = request.headers.get('range')
  if (!range || response.status !== 200) return response
  const body = await response.arrayBuffer()
  const size = body.byteLength
  const match = /bytes=(\\d*)-(\\d*)/.exec(range)
  if (!match) return response
  let start = match[1] === '' ? size - Number(match[2]) : Number(match[1])
  let end = match[1] === '' || match[2] === '' ? size - 1 : Number(match[2])
  start = Math.max(0, start)
  end = Math.min(size - 1, end)
  return new Response(body.slice(start, end + 1), {
    status: 206,
    headers: {
      'Content-Type': response.headers.get('Content-Type') || 'application/octet-stream',
      'Content-Range': 'bytes ' + start + '-' + end + '/' + size,
      'Content-Length': String(end - start + 1),
      'Accept-Ranges': 'bytes',
    },
  })
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    // Fresh when online, the cached page when not.
    event.respondWith(
      fetch(request).catch(() => caches.match(new URL('index.html', self.registration.scope))),
    )
    return
  }
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => (hit ? ranged(request, hit) : fetch(request))),
  )
})
`
}
